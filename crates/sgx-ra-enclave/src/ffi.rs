#[cfg(test)]
pub(crate) use fake::*;

/// Software stand-ins for the trusted runtime, for host-side unit tests.
///
/// They model the observable contract only (status codes, report_data
/// placement, size arithmetic); they provide no security whatsoever.
#[cfg(test)]
#[cfg_attr(not(feature = "sealed-storage"), allow(dead_code))]
pub(crate) mod fake {
    use super::*;
    use core::cell::Cell;
    use core::sync::atomic::{AtomicU64, Ordering};

    /// Offset of report_data in a report body.
    const REPORT_DATA_OFFSET: usize = 320;
    /// Offset of MRENCLAVE in a report body.
    const MR_ENCLAVE_OFFSET: usize = 64;

    static RAND_COUNTER: AtomicU64 = AtomicU64::new(1);

    std::thread_local! {
        /// When set, the next `sgx_read_rand` fails with this status.
        pub(crate) static FAIL_RAND: Cell<Option<u32>> = const { Cell::new(None) };
    }

    pub(crate) unsafe fn sgx_read_rand(rand: *mut u8, length_in_bytes: usize) -> u32 {
        if let Some(status) = FAIL_RAND.with(Cell::take) {
            return status;
        }
        for i in 0..length_in_bytes {
            let v = RAND_COUNTER.fetch_add(0x9e37_79b9_7f4a_7c15, Ordering::Relaxed);
            // SAFETY: the caller passes a writable buffer of `length_in_bytes`.
            unsafe { rand.add(i).write((v >> 29) as u8 ^ (v >> 7) as u8) };
        }
        0
    }

    pub(crate) unsafe fn sgx_is_within_enclave(addr: *const c_void, _size: usize) -> i32 {
        i32::from(!addr.is_null())
    }

    pub(crate) unsafe fn sgx_create_report(
        target_info: *const RawTargetInfo,
        report_data: *const RawReportData,
        report: *mut RawReport,
    ) -> u32 {
        if report.is_null() {
            return 2;
        }
        let mut raw = [0u8; REPORT_LEN];
        // A recognisable fake MRENCLAVE and MODE64BIT attributes.
        raw[MR_ENCLAVE_OFFSET..MR_ENCLAVE_OFFSET + 32].fill(0xee);
        raw[48] = 0x04;
        if !report_data.is_null() {
            // SAFETY: valid pointer per the SDK contract.
            raw[REPORT_DATA_OFFSET..REPORT_DATA_OFFSET + 64]
                .copy_from_slice(unsafe { &*report_data });
        }
        if !target_info.is_null() {
            // Fake key id: echoes the first target byte.
            // SAFETY: valid pointer per the SDK contract.
            raw[384] = unsafe { (*target_info)[0] };
        }
        // SAFETY: valid pointer per the SDK contract.
        unsafe { report.write(raw) };
        0
    }

    /// Who the fake enclave is: drives `sgx_self_report` and the fake
    /// sealing-key derivation, so tests can simulate a code change, a new
    /// signer, an ISVSVN bump or another CPU.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub(crate) struct FakeEnclave {
        pub(crate) mr_enclave: u8,
        pub(crate) mr_signer: u8,
        pub(crate) isv_prod_id: u16,
        pub(crate) isv_svn: u16,
        pub(crate) cpu: u8,
    }

    impl FakeEnclave {
        pub(crate) const DEFAULT: Self = Self {
            mr_enclave: 0xee,
            mr_signer: 0x51,
            isv_prod_id: 1,
            isv_svn: 1,
            cpu: 0,
        };
    }

    /// Fake OCALL behaviour.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub(crate) enum FakeHost {
        /// A host with working storage.
        Storage,
        /// A host whose ocall table lacks the storage OCALLs (blueprint host).
        NoOcalls,
        /// A host that claims a blob longer than the buffer it filled.
        LiesAboutLength,
    }

    /// The fake host's blob store: (namespace, slot) -> blob.
    pub(crate) type FakeStore = std::collections::BTreeMap<([u8; 32], u32), std::vec::Vec<u8>>;

    std::thread_local! {
        pub(crate) static FAKE_SELF: Cell<FakeEnclave> = const { Cell::new(FakeEnclave::DEFAULT) };
        pub(crate) static FAKE_HOST: Cell<FakeHost> = const { Cell::new(FakeHost::Storage) };
        /// The fake host's blob store: (namespace, slot) -> blob.
        pub(crate) static FAKE_STORE: core::cell::RefCell<FakeStore> =
            const { core::cell::RefCell::new(std::collections::BTreeMap::new()) };
        static SELF_REPORT: core::cell::RefCell<std::boxed::Box<RawReport>> =
            core::cell::RefCell::new(std::boxed::Box::new([0u8; REPORT_LEN]));
    }

    // Layout of sgx_sealed_data_t (sgx_tseal.h, sgx_key.h).
    const KR_KEY_NAME: usize = 0;
    const KR_KEY_POLICY: usize = 2;
    const KR_ISV_SVN: usize = 4;
    const KR_KEY_ID: usize = 40;
    const PLAIN_TEXT_OFFSET: usize = 512;
    const PAYLOAD_SIZE: usize = 528;
    const PAYLOAD_TAG: usize = 544;
    const PAYLOAD: usize = 560;
    const KEYSELECT_SEAL: u16 = 4;

    fn rd16(p: *const u8, off: usize) -> u16 {
        // SAFETY: callers pass a buffer of at least PAYLOAD bytes.
        unsafe { u16::from_le_bytes([*p.add(off), *p.add(off + 1)]) }
    }

    fn rd32(p: *const u8, off: usize) -> u32 {
        let mut b = [0u8; 4];
        // SAFETY: callers pass a buffer of at least PAYLOAD bytes.
        unsafe { core::ptr::copy_nonoverlapping(p.add(off), b.as_mut_ptr(), 4) };
        u32::from_le_bytes(b)
    }

    /// The fake sealing key: a hash of what EGETKEY would mix in.
    fn seal_key(policy: u16, isv_svn: u16, key_id: &[u8]) -> [u8; 32] {
        use sha2::{Digest, Sha256};
        let me = FAKE_SELF.with(Cell::get);
        let identity: &[u8] = &match policy {
            0x0001 => [me.mr_enclave, 0, 0],
            _ => {
                let p = me.isv_prod_id.to_le_bytes();
                [me.mr_signer, p[0], p[1]]
            }
        };
        Sha256::new()
            .chain_update(b"fake-seal-key")
            .chain_update(policy.to_le_bytes())
            .chain_update(identity)
            .chain_update(isv_svn.to_le_bytes())
            .chain_update([me.cpu])
            .chain_update(key_id)
            .finalize()
            .into()
    }

    fn keystream_xor(key: &[u8; 32], data: &mut [u8]) {
        use sha2::{Digest, Sha256};
        for (i, chunk) in data.chunks_mut(32).enumerate() {
            let block = Sha256::new()
                .chain_update(key)
                .chain_update((i as u64).to_le_bytes())
                .finalize();
            for (d, k) in chunk.iter_mut().zip(block) {
                *d ^= k;
            }
        }
    }

    fn tag(key: &[u8; 32], header: &[u8], payload: &[u8]) -> [u8; 16] {
        use sha2::{Digest, Sha256};
        let h = Sha256::new()
            .chain_update(b"fake-seal-tag")
            .chain_update(key)
            .chain_update(header)
            .chain_update(payload)
            .finalize();
        h[..16].try_into().unwrap()
    }

    pub(crate) unsafe fn sgx_self_report() -> *const RawReport {
        let me = FAKE_SELF.with(Cell::get);
        SELF_REPORT.with(|r| {
            let mut r = r.borrow_mut();
            r.fill(0);
            r[48] = 0x04;
            r[MR_ENCLAVE_OFFSET..MR_ENCLAVE_OFFSET + 32].fill(me.mr_enclave);
            r[128..160].fill(me.mr_signer);
            r[256..258].copy_from_slice(&me.isv_prod_id.to_le_bytes());
            r[258..260].copy_from_slice(&me.isv_svn.to_le_bytes());
            &**r as *const RawReport
        })
    }

    pub(crate) unsafe fn sgx_calc_sealed_data_size(add: u32, enc: u32) -> u32 {
        560u32
            .checked_add(add)
            .and_then(|n| n.checked_add(enc))
            .unwrap_or(u32::MAX)
    }

    pub(crate) unsafe fn sgx_get_add_mac_txt_len(sealed: *const u8) -> u32 {
        if sealed.is_null() {
            return u32::MAX;
        }
        let (offset, size) = (rd32(sealed, PLAIN_TEXT_OFFSET), rd32(sealed, PAYLOAD_SIZE));
        if offset > size {
            u32::MAX
        } else {
            size - offset
        }
    }

    pub(crate) unsafe fn sgx_get_encrypt_txt_len(sealed: *const u8) -> u32 {
        if sealed.is_null() {
            return u32::MAX;
        }
        let (offset, size) = (rd32(sealed, PLAIN_TEXT_OFFSET), rd32(sealed, PAYLOAD_SIZE));
        if offset > size { u32::MAX } else { offset }
    }

    #[allow(clippy::too_many_arguments)]
    pub(crate) unsafe fn sgx_seal_data_ex(
        key_policy: u16,
        _attribute_mask: Attributes,
        _misc_mask: u32,
        add_len: u32,
        add: *const u8,
        enc_len: u32,
        enc: *const u8,
        sealed_size: u32,
        sealed: *mut u8,
    ) -> u32 {
        if !matches!(key_policy, 0x0001 | 0x0002)
            || enc_len == 0
            || enc.is_null()
            || (add_len != 0 && add.is_null())
            || sealed_size as usize != PAYLOAD + add_len as usize + enc_len as usize
        {
            return 2;
        }
        let me = FAKE_SELF.with(Cell::get);
        let mut key_id = [0u8; 32];
        // SAFETY: valid buffer.
        unsafe { sgx_read_rand(key_id.as_mut_ptr(), 32) };
        // SAFETY: the caller passes `sealed_size` writable bytes and the
        // input lengths.
        let out = unsafe { core::slice::from_raw_parts_mut(sealed, sealed_size as usize) };
        out.fill(0);
        out[KR_KEY_NAME..KR_KEY_NAME + 2].copy_from_slice(&KEYSELECT_SEAL.to_le_bytes());
        out[KR_KEY_POLICY..KR_KEY_POLICY + 2].copy_from_slice(&key_policy.to_le_bytes());
        out[KR_ISV_SVN..KR_ISV_SVN + 2].copy_from_slice(&me.isv_svn.to_le_bytes());
        out[KR_KEY_ID..KR_KEY_ID + 32].copy_from_slice(&key_id);
        out[PLAIN_TEXT_OFFSET..PLAIN_TEXT_OFFSET + 4].copy_from_slice(&enc_len.to_le_bytes());
        out[PAYLOAD_SIZE..PAYLOAD_SIZE + 4].copy_from_slice(&(enc_len + add_len).to_le_bytes());
        let enc_end = PAYLOAD + enc_len as usize;
        // SAFETY: as above.
        out[PAYLOAD..enc_end]
            .copy_from_slice(unsafe { core::slice::from_raw_parts(enc, enc_len as usize) });
        if add_len != 0 {
            // SAFETY: as above.
            out[enc_end..]
                .copy_from_slice(unsafe { core::slice::from_raw_parts(add, add_len as usize) });
        }
        let key = seal_key(key_policy, me.isv_svn, &key_id);
        keystream_xor(&key, &mut out[PAYLOAD..enc_end]);
        let t = tag(&key, &out[..PAYLOAD_TAG], &out[PAYLOAD..]);
        out[PAYLOAD_TAG..PAYLOAD].copy_from_slice(&t);
        0
    }

    pub(crate) unsafe fn sgx_unseal_data(
        sealed: *const u8,
        add: *mut u8,
        add_len: *mut u32,
        dec: *mut u8,
        dec_len: *mut u32,
    ) -> u32 {
        if sealed.is_null() || dec.is_null() || dec_len.is_null() {
            return 2;
        }
        // SAFETY: the SDK contract: `sealed` holds a blob as long as its
        // header says (the caller checked that).
        let (enc_n, add_n) = unsafe {
            (
                sgx_get_encrypt_txt_len(sealed),
                sgx_get_add_mac_txt_len(sealed),
            )
        };
        if enc_n == u32::MAX || add_n == u32::MAX {
            return 2;
        }
        // SAFETY: valid out-pointers per the contract.
        unsafe {
            if *dec_len < enc_n
                || (add_n != 0 && (add.is_null() || add_len.is_null() || *add_len < add_n))
            {
                return 2;
            }
        }
        let total = PAYLOAD + (enc_n + add_n) as usize;
        // SAFETY: see above.
        let blob = unsafe { core::slice::from_raw_parts(sealed, total) };
        if rd16(sealed, KR_KEY_NAME) != KEYSELECT_SEAL {
            return 0x4003; // SGX_ERROR_INVALID_KEYNAME
        }
        let me = FAKE_SELF.with(Cell::get);
        let svn = rd16(sealed, KR_ISV_SVN);
        if svn > me.isv_svn {
            return 0x4002; // SGX_ERROR_INVALID_ISVSVN
        }
        let policy = rd16(sealed, KR_KEY_POLICY);
        let key = seal_key(policy, svn, &blob[KR_KEY_ID..KR_KEY_ID + 32]);
        if tag(&key, &blob[..PAYLOAD_TAG], &blob[PAYLOAD..]) != blob[PAYLOAD_TAG..PAYLOAD] {
            return 0x3001; // SGX_ERROR_MAC_MISMATCH
        }
        let enc_end = PAYLOAD + enc_n as usize;
        let mut plain = blob[PAYLOAD..enc_end].to_vec();
        keystream_xor(&key, &mut plain);
        // SAFETY: capacities checked above.
        unsafe {
            core::ptr::copy_nonoverlapping(plain.as_ptr(), dec, plain.len());
            *dec_len = enc_n;
            if add_n != 0 {
                core::ptr::copy_nonoverlapping(blob[enc_end..].as_ptr(), add, add_n as usize);
            }
            if !add_len.is_null() {
                *add_len = add_n;
            }
        }
        0
    }

    pub(crate) unsafe fn sgx_ra_ocall_load_sealed(
        retval: *mut u32,
        p_namespace: *const u8,
        slot: u32,
        p_blob: *mut u8,
        capacity: usize,
        p_blob_len: *mut usize,
    ) -> u32 {
        let host = FAKE_HOST.with(Cell::get);
        if host == FakeHost::NoOcalls {
            return 0x1001; // SGX_ERROR_INVALID_FUNCTION
        }
        // SAFETY: the bridge contract: 32-byte namespace, `capacity`
        // writable bytes, writable out-pointers.
        let ns: [u8; 32] = unsafe { *p_namespace.cast() };
        let found = FAKE_STORE.with(|s| s.borrow().get(&(ns, slot)).cloned());
        let status = match found {
            None => 1,
            Some(blob) if blob.len() > capacity => 3,
            Some(blob) => {
                // SAFETY: see above.
                unsafe {
                    core::ptr::copy_nonoverlapping(blob.as_ptr(), p_blob, blob.len());
                    *p_blob_len = if host == FakeHost::LiesAboutLength {
                        capacity + 1
                    } else {
                        blob.len()
                    };
                }
                0
            }
        };
        // SAFETY: see above.
        unsafe { *retval = status };
        0
    }

    pub(crate) unsafe fn sgx_ra_ocall_store_sealed(
        retval: *mut u32,
        p_namespace: *const u8,
        slot: u32,
        p_blob: *const u8,
        blob_len: usize,
        replace: u32,
    ) -> u32 {
        if FAKE_HOST.with(Cell::get) == FakeHost::NoOcalls {
            return 0x1001;
        }
        // SAFETY: the bridge contract.
        let ns: [u8; 32] = unsafe { *p_namespace.cast() };
        // SAFETY: the bridge contract.
        let blob = unsafe { core::slice::from_raw_parts(p_blob, blob_len) }.to_vec();
        let status = FAKE_STORE.with(|s| {
            let mut s = s.borrow_mut();
            if replace == 0 && s.contains_key(&(ns, slot)) {
                2
            } else {
                s.insert((ns, slot), blob);
                0
            }
        });
        // SAFETY: the bridge contract.
        unsafe { *retval = status };
        0
    }
}
